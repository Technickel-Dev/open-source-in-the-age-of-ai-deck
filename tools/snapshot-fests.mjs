// Refreshes data/fests.js from the public MLH events API (the same data hacktoberfest.com/fests renders).
// Usage: node tools/snapshot-fests.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const res = await fetch('https://hacktoberfest-api.mlh.com/api/events');
if (!res.ok) throw new Error(`events API returned ${res.status}`);
const { events } = await res.json();

const located = events.filter((e) => e.address && e.address.latitude != null);
const kind = (e) => (e.kind === 'fest' ? 'fest' : e.kind === 'popup' ? 'popup' : 'member');
const data = {
  asOf: new Date().toISOString().slice(0, 10),
  total: events.length,
  countries: new Set(located.map((e) => e.address.country)).size,
  points: located.map((e) => [+e.address.latitude.toFixed(3), +e.address.longitude.toFixed(3), kind(e)]),
};

fs.writeFileSync(
  path.join(root, 'data', 'fests.js'),
  `// Generated by tools/snapshot-fests.mjs from https://hacktoberfest-api.mlh.com/api/events\nwindow.FESTS = ${JSON.stringify(data)};\n`
);
console.log(`${data.total} events, ${data.points.length} located, ${data.countries} countries (as of ${data.asOf})`);
